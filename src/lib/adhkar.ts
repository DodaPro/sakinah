/** أذكار الصباح (٢٢ ذكرًا) */
export const AZKAR_MORNING: AzkarItem[] = baseList("صباح");

/** أذكار المساء (٢٢ ذكرًا) */
export const AZKAR_EVENING: AzkarItem[] = baseList("مساء");

export function azkarList(period: AzkarPeriod): AzkarItem[] {
  return period === "morning" ? AZKAR_MORNING : AZKAR_EVENING;
}

/* ---------------- العدّادات اليومية (لكل فترة) ---------------- */

type AzkarStore = Record<string, number[]>; // { "morning|2025-01-01": [counts] }

const K_AZKAR = "sakinah.azkar";

function azkarKey(period: AzkarPeriod, iso: string) {
  return `${period}|${iso}`;
}

export function loadAzkarCounts(period: AzkarPeriod, iso: string): number[] {
  if (typeof window === "undefined") return azkarList(period).map(() => 0);
  try {
    const raw = window.localStorage.getItem(K_AZKAR);
    const store: AzkarStore = raw ? JSON.parse(raw) : {};
    const arr = store[azkarKey(period, iso)];
    if (!Array.isArray(arr)) return azkarList(period).map(() => 0);
    return azkarList(period).map((_, i) => (typeof arr[i] === "number" ? arr[i] : 0));
  } catch {
    return azkarList(period).map(() => 0);
  }
}

export function saveAzkarCounts(period: AzkarPeriod, iso: string, counts: number[]) {
  if (typeof window === "undefined") return;
  try {
    const raw = window.localStorage.getItem(K_AZKAR);
    const store: AzkarStore = raw ? JSON.parse(raw) : {};
    // ننضف الأيام الأقدم من ٩٠ يوم لتخفيف التخزين
    const today = isoOf(new Date());
    for (const k of Object.keys(store)) {
      const d = k.split("|")[1];
      if (d && d < today) {
        const diff = (new Date(today).getTime() - new Date(d).getTime()) / 864e5;
        if (diff > 90) delete store[k];
      }
    }
    store[azkarKey(period, iso)] = counts;
    window.localStorage.setItem(K_AZKAR, JSON.stringify(store));
  } catch {}
}
